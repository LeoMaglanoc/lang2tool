import fs from 'node:fs';
import { gzipSync } from 'node:zlib';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { OBJLoader } from 'three/addons/loaders/OBJLoader.js';
import { STLLoader } from 'three/addons/loaders/STLLoader.js';
import { mergeGeometries, mergeVertices } from 'three/addons/utils/BufferGeometryUtils.js';
const demo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const root = path.resolve(demo, '..');
const sources = JSON.parse(fs.readFileSync(path.join(demo, '.export/meshes.json'), 'utf8'));
const catalog = {};
// Pack indexed positions/normals into compact buffers, keeping source geometry unchanged.
for (const [id, info] of Object.entries(sources)) {
  const bytes = fs.readFileSync(path.join(root, info.source));
  let geometry;
  if (info.format === '.obj') {
    const object = new OBJLoader().parse(bytes.toString('utf8'));
    const parts = [];
    object.updateMatrixWorld(true);
    object.traverse(child => { if (child.isMesh) parts.push(child.geometry.clone().applyMatrix4(child.matrixWorld)); });
    geometry = mergeGeometries(parts);
  } else geometry = new STLLoader().parse(bytes.buffer.slice(bytes.byteOffset, bytes.byteOffset + bytes.byteLength));
  geometry.deleteAttribute('uv'); geometry.deleteAttribute('color');
  if (!geometry.getAttribute('normal')) geometry.computeVertexNormals();
  geometry = mergeVertices(geometry, 1e-7);
  const position = Float32Array.from(geometry.getAttribute('position').array);
  const normal = Float32Array.from(geometry.getAttribute('normal').array);
  const indices = Uint32Array.from(geometry.index.array);
  const buffer = Buffer.concat([Buffer.from(position.buffer), Buffer.from(normal.buffer), Buffer.from(indices.buffer)]);
  fs.writeFileSync(path.join(demo, 'public/assets', id + '.mesh'), gzipSync(buffer));
  geometry.computeBoundingBox();
  catalog[id] = {vertices: position.length / 3, indices: indices.length, file: `assets/${id}.mesh`, source: info.source, sha256: info.sha256, bounds: [geometry.boundingBox.min.toArray(), geometry.boundingBox.max.toArray()]};
}
fs.writeFileSync(path.join(demo, 'public/assets/meshes.json'), JSON.stringify(catalog) + '\n');
console.log(`Packed ${Object.keys(catalog).length} meshes`);
// Remove only obsolete raw buffers generated by earlier versions of this exporter.
for (const id of Object.keys(sources)) {
  const old = path.join(demo, 'public/assets', id + '.bin');
  if (fs.existsSync(old)) fs.unlinkSync(old);
}
for (const id of Object.keys(sources)) {
  const old = path.join(demo, 'public/assets', id + '.bin.gz');
  if (fs.existsSync(old)) fs.unlinkSync(old);
}
